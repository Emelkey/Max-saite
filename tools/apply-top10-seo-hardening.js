const escapeHtml = (value) =>
  value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

const faqHtml = (items) =>
  items.map(([question, answer]) => `<details><summary>${escapeHtml(question)}</summary><p>${escapeHtml(answer)}</p></details>`).join("");

for (const [slug, article] of Object.entries(articles)) {
  const file = path.join(root, "blog", slug, "index.html");
  let html = fs.readFileSync(file, "utf8");
  const articleHtml = [
    `<article class="article-body">`,
    `<p class="article-meta"><time datetime="${modified}">Оновлено ${modified.split("-").reverse().join(".")}</time> · MAX SITE</p>`,
    `<p>${escapeHtml(article.intro)}</p>`,
    ...article.sections.map(([heading, text]) => `<h2>${escapeHtml(heading)}</h2><p>${escapeHtml(text)}</p>`),
    `<h2>Пов’язані матеріали та послуги</h2>`,
    `<p><a href="/stvorennya-saytiv/">Створення сайтів під ключ</a>, <a href="/seo-sajt-pid-google/">SEO-сайт під Google</a>, <a href="/google-ads/">Google Ads</a>, <a href="/portfolio/">портфоліо MAX SITE</a> та <a href="/kontakty/">контакти</a>.</p>`,
    `</article>`,
  ].join("");

  if (!/<article class="article-body">[\s\S]*?<\/article>/.test(html)) {
    throw new Error(`Article body not found: ${slug}`);
  }
  html = html.replace(/<article class="article-body">[\s\S]*?<\/article>/, articleHtml);

  const faqSection = `<section class="seo-band"><h2>FAQ</h2><div class="faq-list reveal">${faqHtml(article.faq)}</div></section>`;
  if (!/<section class="seo-band"><h2>FAQ<\/h2>[\s\S]*?<\/section><section class="seo-lead"/.test(html)) {
    throw new Error(`FAQ section not found: ${slug}`);
  }
  html = html.replace(
    /<section class="seo-band"><h2>FAQ<\/h2>[\s\S]*?<\/section>(?=<section class="seo-lead")/,
    faqSection
  );

  html = html.replace(
    /<script type="application\/ld\+json">([\s\S]*?)<\/script>/,
    (full, json) => {
      const data = JSON.parse(json);
      const graph = data["@graph"] || [];
      const organization = graph.find((item) => item["@type"] === "Organization");
      if (organization) {
        organization.logo = `${siteUrl}/assets/logo-header.svg`;
        organization.sameAs = ["https://t.me/MaxMytt", "https://www.instagram.com/maxlab.ai/"];
      }
      const item = graph.find((entry) => entry["@type"] === "Article");
      if (!item) throw new Error(`Article schema not found: ${slug}`);
      item.datePublished = published;
      item.dateModified = modified;
      item.author = { "@id": `${siteUrl}/#organization` };
      item.publisher = { "@id": `${siteUrl}/#organization` };
      item.image = `${siteUrl}/assets/og-max-site.png`;
      item.mainEntityOfPage = `${siteUrl}/blog/${slug}/`;
      const schemaFaq = graph.find((entry) => entry["@type"] === "FAQPage");
      if (schemaFaq) {
        schemaFaq.mainEntity = article.faq.map(([question, answer]) => ({
          "@type": "Question",
          name: question,
          acceptedAnswer: { "@type": "Answer", text: answer },
        }));
      }
      return `<script type="application/ld+json">${JSON.stringify(data)}</script>`;
    }
  );

  fs.writeFileSync(file, html);
}

