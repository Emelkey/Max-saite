const collectFiles = (directory, extensions) => {
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if ([".git", "release", "node_modules"].includes(entry.name)) continue;
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...collectFiles(file, extensions));
    else if (extensions.some((extension) => entry.name.endsWith(extension))) files.push(file);
  }
  return files;
};

for (const file of collectFiles(root, [".html", ".js"])) {
  if (file === __filename) continue;
  let content = fs.readFileSync(file, "utf8");
  const original = content;
  for (const [from, to] of routeMap) content = content.replaceAll(from, to);
  if (content !== original) fs.writeFileSync(file, content);
}

